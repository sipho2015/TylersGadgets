// Development-only image preparation. No image library is shipped to the browser.
// Pass the installed sharp entrypoint, e.g. .verification/tools/node_modules/sharp/dist/index.mjs.
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
const entry=process.argv[2];
if(!entry)throw Error('Pass a local sharp module entrypoint. See README.md.');
const sharp=(await import(pathToFileURL(path.resolve(entry)).href)).default;
const walk=dir=>fs.readdirSync(dir,{withFileTypes:true}).flatMap(item=>item.isDirectory()?walk(dir+'/'+item.name):[dir+'/'+item.name]);
const files=walk('assets').filter(file=>/\.(jpe?g|png)$/i.test(file)&&!file.startsWith('assets/optimized/'));
fs.mkdirSync('assets/optimized',{recursive:true});
const manifest={},processed=new Map();let originalBytes=0,optimizedBytes=0;
for(const file of files){
 const bytes=fs.readFileSync(file),hash=createHash('sha256').update(bytes).digest('hex').slice(0,16);
 if(processed.has(hash)){manifest[file]=processed.get(hash);continue;}
 const meta=await sharp(bytes).rotate().metadata();
 const portrait=[5,6,7,8].includes(meta.orientation),width=portrait?meta.height:meta.width,height=portrait?meta.width:meta.height;
 const variants=[];
 for(const size of [...new Set([100,400,800,Math.min(width,1400)].map(size=>Math.min(size,width)))].sort((a,b)=>a-b)){
  const output=`assets/optimized/${hash}-${size}.webp`;
  await sharp(bytes).rotate().resize({width:size,withoutEnlargement:true}).webp({quality:78,effort:4}).toFile(output);
  variants.push({src:output,width:size});optimizedBytes+=fs.statSync(output).size;
 }
 const value={width,height,src:variants.find(item=>item.width>=800)?.src||variants.at(-1).src,variants};manifest[file]=value;processed.set(hash,value);originalBytes+=bytes.length;
}
fs.writeFileSync('src/core/image-manifest.js','// Generated by scripts/optimize-images.mjs; original photographs are preserved.\nexport const imageManifest='+JSON.stringify(manifest,null,2)+';\n');
console.log(JSON.stringify({photographs:files.length,unique:processed.size,originalBytes,optimizedBytes},null,2));
